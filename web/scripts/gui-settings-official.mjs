import { chromium } from 'playwright-core';
const exe = process.env.CHROMIUM_PATH || '/home/kele/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome';
const base = process.env.APUI_URL || 'http://192.168.101.133:7778/';
const out = process.env.OUT_DIR || '/home/kele/aplayer/gui-test-screenshots';
const errors = [];
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto(base, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2200);
await page.getByRole('link', { name: /设置/ }).first().click();
await page.waitForTimeout(900);
console.log('MAIN_TABS', await page.locator('.settings-nav-btn').allTextContents());
await page.screenshot({ path: `${out}/s01-general.png`, fullPage: true });

const tab = async (name) => { await page.locator('.settings-nav-btn').filter({ hasText: name }).first().click(); await page.waitForTimeout(350); };
const sub = async (name) => { await page.locator('.settings-subtabs .tab-btn').filter({ hasText: name }).first().click(); await page.waitForTimeout(300); };
const has = async (text) => (await page.locator('body').innerText()).includes(text);

console.log('GENERAL_PRELOAD', await has('Preload buffer (frames)'));
console.log('GENERAL_HWPARAM', await has('HW parameter'));
console.log('GENERAL_BUFFER', await has('Buffer Access'));
await tab('Decoder'); await sub('DSD');
console.log('DSD_CONVERTER', await has('DSD to PCM converter'));
console.log('DSD_FULLDISK', await has('Full disk mode'));
await page.screenshot({ path: `${out}/s02-decoder-dsd.png`, fullPage: true });
await sub('DVD-A'); console.log('DVDA', await has("Don't load stereo downmixes"));
await sub('Radio'); console.log('RADIO_UPDATE', await has('Update Catalog')); console.log('RADIO_STDBUFFER', await has('Preload buffer (frames)'));
await page.screenshot({ path: `${out}/s03-decoder-radio.png`, fullPage: true });
await tab('DSP'); await sub('Converter');
console.log('CONVERTER_DSD', await has('Convert PCM to DSD'));
await sub('Resampler'); console.log('RESAMPLER', await has('< 44 KHz'), await has('Steep filter (99%)'), await has('Attenuate, dB -'));
await page.screenshot({ path: `${out}/s04-dsp-resampler.png`, fullPage: true });
await sub('Convolver'); console.log('CONVOLVER', await has('Enable convolver'), await has('Filters'));
await tab('System'); console.log('SYSTEM', await has('Process Priority (0–99)'), await has('Selecting cores'));
await tab('Status'); console.log('STATUS', await has('Supports Native DSD'), await has('ALSA Period'));
await page.screenshot({ path: `${out}/s05-status.png`, fullPage: true });
await tab('Card'); console.log('CARD', await has('Available cards'), await has('Scream'), await has('Receiver IP'));
await page.screenshot({ path: `${out}/s06-card.png`, fullPage: true });
await tab('About'); console.log('ABOUT', await has('APUI 0.2.0'), await has('Apache License 2.0'), await has('Igor Antonov'));
await page.screenshot({ path: `${out}/s07-about.png`, fullPage: true });

// Save test on General: Play silence 5 -> save -> verify -> 0 -> save
await tab('General');
const silenceRow = page.locator('.setting-row').filter({ hasText: 'Play silence (ms)' }).first();
const silence = silenceRow.locator('input');
await silence.fill('5');
await page.locator('.settings-header .page-actions .btn-primary').click();
await page.waitForTimeout(1200);
const cfg = await (await fetch(base + '?GetConfig')).json();
console.log('SAVE_SILENCE', cfg.si_time, 'COVERS', cfg.covers, 'ROOT', cfg.root_folder);
await silence.fill('0');
await page.locator('.settings-header .page-actions .btn-primary').click();
await page.waitForTimeout(1000);
const cfg2 = await (await fetch(base + '?GetConfig')).json();
console.log('RESTORE_SILENCE', cfg2.si_time);
console.log('ERRORS', JSON.stringify(errors));
await browser.close();
