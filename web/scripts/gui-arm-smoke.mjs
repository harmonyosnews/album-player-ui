import { chromium } from 'playwright-core';
const exe = process.env.CHROMIUM_PATH || '/usr/bin/chromium';
const out = process.env.OUT_DIR || './gui-test-screenshots';
const base = process.env.APUI_URL || 'http://127.0.0.1:7778/';
const errors = [];
const bad = [];
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('response', (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url()}`); });
await page.goto(base, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2200);
await page.screenshot({ path: `${out}/arm01-home.png`, fullPage: true });
console.log('TITLE', await page.title());
console.log('HAS_EMPTY', (await page.locator('body').innerText()).includes('媒体库还是空的') || (await page.locator('body').innerText()).includes('没有专辑'));
await page.getByRole('link', { name: /设置/ }).first().click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/arm02-settings.png`, fullPage: true });
console.log('SETTINGS_ROOT', (await page.locator('body').innerText()).includes('音乐根目录'));
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/arm03-mobile.png`, fullPage: true });
console.log('MOBILE_NAV', await page.locator('.mobile-nav').isVisible());
console.log('ERRORS', JSON.stringify(errors));
console.log('BAD', JSON.stringify(bad.slice(0, 10)));
await browser.close();
